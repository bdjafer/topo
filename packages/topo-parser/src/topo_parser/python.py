"""
Python source code parser.

Walks a Python codebase using the ast module and produces a CodeGraph
with nodes (modules, classes, functions) and edges (calls, imports,
inheritance, containment).

Call graph generation is delegated to PyCG (vendored), which performs
inter-procedural analysis with assignment tracking to resolve calls
including obj.method(), cross-module imports, and closures.
"""

from __future__ import annotations

import ast
import logging
import os
from pathlib import Path

from topo_parser.ast_resolve import (
    _resolve_call_edges_ast,
    _resolve_inherits_edges,
    _resolve_name,
    _try_resolve,
)
from topo_parser.graph import CodeGraph, Edge, EdgeKind, Node, NodeKind

logger = logging.getLogger(__name__)


def parse_python_project(
    root: Path,
    exclude_patterns: list[str] | None = None,
    include_roots: list[Path] | None = None,
) -> CodeGraph:
    """
    Parse a Python project directory into a CodeGraph.

    Walks all .py files under `root`, extracts entities and relationships.
    Detects src-layout packages and uses the Python package root for module IDs.
    Call edges are generated by PyCG's inter-procedural analysis.

    Args:
        root: Path to project directory.
        exclude_patterns: Directory/file name patterns to exclude (e.g. ["pycg", ".venv"]).
            Any .py file whose path contains a matching component is skipped.
        include_roots: Optional sub-roots to include instead of walking the full tree.
    """
    graph = CodeGraph()
    root = root.resolve()
    py_files = _discover_python_files(root, include_roots)

    if exclude_patterns:
        py_files = [
            f for f in py_files
            if not any(pat in f.relative_to(root).parts for pat in exclude_patterns)
        ]

    # Detect Python package roots: directories containing __init__.py that
    # aren't nested inside another package. Handles both flat layout
    # (root/pkg/__init__.py) and src layout (root/src/pkg/__init__.py).
    package_roots = _find_package_roots(root, py_files)

    for py_file in py_files:
        try:
            source = py_file.read_text(encoding="utf-8")
            tree = ast.parse(source, filename=str(py_file))
        except (SyntaxError, UnicodeDecodeError):
            continue

        pkg_root = _best_package_root(py_file, package_roots)
        _extract_from_file(graph, tree, py_file, pkg_root or root)

    # Use PyCG for call edges (inter-procedural analysis with type inference),
    # falling back to AST-based resolution if PyCG fails.
    pycg_calls = _extract_calls_pycg(root, py_files, package_roots)
    if pycg_calls is not None:
        _add_pycg_calls(graph, pycg_calls)
        # PyCG doesn't resolve super().method() — supplement with AST
        _add_super_calls_ast(graph, root, py_files, package_roots)
    else:
        _resolve_call_edges_ast(graph)

    # PyCG doesn't track @property access (it sees attribute access, not
    # function calls).  Supplement with AST-based property resolution.
    _add_property_access_calls(graph, root, py_files, package_roots)

    # Resolve INHERITS edges (always AST-based)
    _resolve_inherits_edges(graph)
    return graph


def _discover_python_files(root: Path, include_roots: list[Path] | None) -> list[Path]:
    """Collect Python files from the requested roots."""
    if not include_roots:
        return sorted(root.rglob("*.py"))

    py_files: list[Path] = []
    seen: set[Path] = set()
    for include_root in include_roots:
        resolved_root = include_root.resolve()
        if not resolved_root.exists():
            continue
        for py_file in resolved_root.rglob("*.py"):
            resolved_file = py_file.resolve()
            if resolved_file not in seen:
                seen.add(resolved_file)
                py_files.append(resolved_file)
    return sorted(py_files)


def _find_package_roots(root: Path, py_files: list[Path]) -> list[Path]:
    """Find directories that serve as Python package roots.

    A package root is the parent of a top-level Python package. For example,
    in a src layout (proj/src/pkg/__init__.py), the package root is proj/src/.
    In a flat layout (proj/pkg/__init__.py), the package root is proj/.
    """
    # Find all directories containing __init__.py
    init_dirs: set[Path] = set()
    for f in py_files:
        if f.name == "__init__.py":
            init_dirs.add(f.parent.resolve())

    # A package root is the parent of a package dir whose parent is NOT itself a package.
    # This gives us the directory from which Python module IDs should be computed.
    package_roots: set[Path] = set()
    for pkg_dir in init_dirs:
        parent = pkg_dir.parent
        if parent not in init_dirs:
            package_roots.add(parent)

    return sorted(package_roots)


def _best_package_root(file: Path, package_roots: list[Path]) -> Path | None:
    """Find the most specific package root that contains this file."""
    file = file.resolve()
    best: Path | None = None
    for pr in package_roots:
        if file.is_relative_to(pr):
            if best is None or len(pr.parts) > len(best.parts):
                best = pr
    return best


def _module_id(file: Path, root: Path) -> str:
    """Derive a module id from file path relative to root."""
    rel = file.relative_to(root)
    parts = list(rel.with_suffix("").parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts) if parts else rel.stem


_STRUCTURAL_STMT_TYPES = (
    ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef,
    ast.Import, ast.ImportFrom,
)


def _extract_from_file(
    graph: CodeGraph, tree: ast.Module, file: Path, root: Path
) -> None:
    """Extract nodes and edges from a single parsed file.

    Files with no structural content (no classes, functions, or imports)
    are skipped — they are namespace markers, not code entities.
    """
    children = list(ast.iter_child_nodes(tree))

    if not any(isinstance(node, _STRUCTURAL_STMT_TYPES) for node in children):
        return  # Namespace-only file (empty, docstring-only, etc.)

    mod_id = _module_id(file, root)
    graph.add_node(Node(id=mod_id, kind=NodeKind.MODULE, file=str(file), line=1, name=mod_id.split(".")[-1]))

    for node in children:
        if isinstance(node, ast.ClassDef):
            _extract_class(graph, node, mod_id, file)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            _extract_function(graph, node, mod_id, file)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            _extract_import(graph, node, mod_id, file)


def _extract_class(
    graph: CodeGraph, node: ast.ClassDef, parent_id: str, file: Path
) -> None:
    """Extract a class node, its methods, and inheritance edges."""
    class_id = f"{parent_id}.{node.name}"
    graph.add_node(Node(id=class_id, kind=NodeKind.CLASS, file=str(file), line=node.lineno, name=node.name))
    graph.add_edge(Edge(source=parent_id, target=class_id, kind=EdgeKind.CONTAINS))

    # Inheritance (raw names, resolved later by _resolve_inherits_edges)
    for base in node.bases:
        base_name = _resolve_name(base)
        if base_name:
            graph.add_edge(Edge(source=class_id, target=base_name, kind=EdgeKind.INHERITS))

    # Methods
    for child in ast.iter_child_nodes(node):
        if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
            _extract_function(graph, child, class_id, file)


def _extract_function(
    graph: CodeGraph,
    node: ast.FunctionDef | ast.AsyncFunctionDef,
    parent_id: str,
    file: Path,
) -> None:
    """Extract a function/method node. Call edges are added by PyCG."""
    func_id = f"{parent_id}.{node.name}"
    graph.add_node(Node(id=func_id, kind=NodeKind.FUNCTION, file=str(file), line=node.lineno, name=node.name))
    graph.add_edge(Edge(source=parent_id, target=func_id, kind=EdgeKind.CONTAINS))


def _resolve_relative_import(
    mod_id: str, file: Path, level: int, module: str | None,
) -> str | None:
    """Resolve a relative import to a fully-qualified module path.

    Args:
        mod_id: Fully-qualified ID of the importing module.
        file: Path to the importing file (needed to detect __init__.py).
        level: Number of dots in the relative import (1 = current package).
        module: The module part of ``from .module import name`` (may be None).

    Returns:
        Fully-qualified module path, or None if the import goes above the root.
    """
    if file.name == "__init__.py":
        package_parts = mod_id.split(".")
    else:
        package_parts = mod_id.rsplit(".", 1)[0].split(".") if "." in mod_id else []

    levels_up = level - 1
    if levels_up >= len(package_parts):
        return None
    if levels_up > 0:
        package_parts = package_parts[:-levels_up]

    base = ".".join(package_parts)
    if module:
        return f"{base}.{module}" if base else module
    return base or None


def _extract_import(
    graph: CodeGraph, node: ast.Import | ast.ImportFrom, mod_id: str, file: Path,
) -> None:
    """Extract import edges with fully-qualified targets.

    For ``import foo.bar``, creates an edge to ``foo.bar``.
    For ``from foo.bar import baz``, creates edges to ``foo.bar`` and ``foo.bar.baz``.
    For relative imports (``from .foo import bar``), resolves the target using
    the importing module's position in the package hierarchy.
    """
    if isinstance(node, ast.Import):
        for alias in node.names:
            graph.add_edge(Edge(source=mod_id, target=alias.name, kind=EdgeKind.IMPORTS))
        return

    if isinstance(node, ast.ImportFrom) and node.level > 0:
        base = _resolve_relative_import(mod_id, file, node.level, node.module)
    elif node.module:
        base = node.module
    else:
        return

    if base is None:
        return

    graph.add_edge(Edge(source=mod_id, target=base, kind=EdgeKind.IMPORTS))
    for alias in node.names:
        if alias.name != "*":
            graph.add_edge(Edge(source=mod_id, target=f"{base}.{alias.name}", kind=EdgeKind.IMPORTS))


